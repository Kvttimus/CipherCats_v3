"""Generate supabase/seed.sql from backend/content.

    cd backend && python -m scripts.gen_seed
"""

from __future__ import annotations

import json
from pathlib import Path

from content import STORYLINES

OUT = Path(__file__).resolve().parents[2] / "supabase" / "seed.sql"


def q(value) -> str:
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def qjson(value) -> str:
    return q(json.dumps(value, ensure_ascii=False)) + "::jsonb"


def qarray(values: list[str]) -> str:
    return "array[" + ", ".join(q(v) for v in values) + "]::text[]" if values else "'{}'::text[]"


def storyline_sql(s: dict) -> str:
    return f"""insert into public.storylines (slug, title, theme, vibe, description, difficulty, available, reward, preview, order_index)
values ({q(s['slug'])}, {q(s['title'])}, {q(s['theme'])}, {q(s['vibe'])}, {q(s['description'])}, {q(s['difficulty'])}, {q(s.get('available', False))}, {q(s.get('reward'))}, {qjson(s.get('preview', []))}, {s['order_index']})
on conflict (slug) do update set
  title = excluded.title, theme = excluded.theme, vibe = excluded.vibe,
  description = excluded.description, difficulty = excluded.difficulty,
  available = excluded.available, reward = excluded.reward,
  preview = excluded.preview, order_index = excluded.order_index;
"""


def lab_sql(storyline_slug: str, index: int, lab: dict) -> str:
    return f"""insert into public.labs (storyline_id, slug, title, description, story_segment, challenge_prompt, cipher_type, payload, skills, is_boss, order_index, xp_reward)
select s.id, {q(lab['slug'])}, {q(lab['title'])}, {q(lab['description'])}, {q(lab['story_segment'])}, {q(lab['challenge_prompt'])}, {q(lab['cipher_type'])},
  {qjson(lab['payload'])},
  {qarray(lab['skills'])}, {q(lab.get('is_boss', False))}, {index}, {lab['xp_reward']}
from public.storylines s where s.slug = {q(storyline_slug)}
on conflict (slug) do update set
  storyline_id = excluded.storyline_id, title = excluded.title, description = excluded.description,
  story_segment = excluded.story_segment, challenge_prompt = excluded.challenge_prompt,
  cipher_type = excluded.cipher_type, payload = excluded.payload, skills = excluded.skills,
  is_boss = excluded.is_boss, order_index = excluded.order_index, xp_reward = excluded.xp_reward;

insert into public.lab_solutions (lab_id, solution, hints)
select id, {q(lab['solution'])}, {qjson(lab['hints'])} from public.labs where slug = {q(lab['slug'])}
on conflict (lab_id) do update set solution = excluded.solution, hints = excluded.hints;
"""


def main() -> None:
    parts = [
        "-- CipherCats seed data. GENERATED by backend/scripts/gen_seed.py; edit backend/content instead.\n"
        "-- Run AFTER schema.sql and policies.sql. Safe to re-run (upserts).\n"
    ]
    for s in STORYLINES:
        parts.append(f"\n-- ===== {s['title']} =====\n")
        parts.append(storyline_sql(s))
        for i, lab in enumerate(s.get("labs", []), start=1):
            parts.append(f"\n-- Lab {i}: {lab['title']}\n")
            parts.append(lab_sql(s["slug"], i, lab))
    OUT.write_text("".join(parts), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
